// Verified backup of a stopped HomeAI installation. No recursive link traversal.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const [rootArg,destinationArg]=process.argv.slice(2),root=path.resolve(rootArg),destination=path.resolve(destinationArg);
function under(base,target){const full=path.resolve(target);if(full!==base&&!full.startsWith(base+path.sep))throw Error('Backup path escapes its root.');return full;}
function noLinks(file){for(let cursor=file;;cursor=path.dirname(cursor)){try{if(fs.lstatSync(cursor).isSymbolicLink())throw Error('Backup refuses links: '+cursor);}catch(e){if(e.code!=='ENOENT')throw e;}if(path.dirname(cursor)===cursor)break;}}
noLinks(root);noLinks(destination);
const settings=JSON.parse(fs.readFileSync(path.join(root,'homeai.json'),'utf8').replace(/^\uFEFF/,''));
if(settings.owner!=='home-ai-kit-v1'||path.resolve(settings.root)!==root)throw Error('Backup installation ownership differs.');
const backupRoot=path.resolve(settings.backupRoot);
if(destination===backupRoot||path.dirname(destination)!==backupRoot||!/^\d{8}-\d{6}-[a-f0-9]{8}$/.test(path.basename(destination)))throw Error('Backup target must be a new named snapshot directly under backupRoot.');
if(backupRoot===root||backupRoot.startsWith(root+path.sep)||root.startsWith(backupRoot+path.sep))throw Error('Backup root and installation must not overlap.');
if(!fs.statSync(destination).isDirectory()||fs.readdirSync(destination).length)throw Error('Snapshot target must be an empty directory.');
const exclusions=new Map([
 ['projects\\orchestrator\\data\\private','Private local sessions must never be backed up'],
 ['projects\\orchestrator\\data\\scratch','Transient model prompt scratch files'],
 ['state\\openclaw\\plugin-skills','OpenClaw-generated plugin skill links; regenerated from installed plugins'],
 ['state\\openclaw\\npm\\projects','OpenClaw-generated npm dependency projects and host-package links; reinstall recorded plugin packages to restore runtimes'],
 ['state\\openclaw\\tmp\\plugin-captures','OpenClaw temporary plugin build/model-catalog captures; regenerated by the runtime'],
 ['state\\openclaw\\sandbox\\skills-workspaces','OpenClaw-generated sandbox skill workspaces; regenerated by the runtime'],
 ['state\\openclaw\\cache\\control-ui-assets','OpenClaw-generated control UI asset cache; regenerated by the runtime']
]);
const items=['homeai.json','state','workspace','projects','output','scripts','evaluations'];
let files=0,bytes=0,folders=0,last=0;const started=Date.now(),excluded=[];
function progress(force=false){const now=Date.now();if(force||now-last>=5000){process.stdout.write('Backup: '+files+' verified files; '+(bytes/1024**3).toFixed(2)+' GiB; '+folders+' folders; '+Math.round((now-started)/1000)+' seconds.\n');last=now;}}
const buffer=Buffer.allocUnsafe(1024*1024);
function hashedCopy(source,target){
  // Keep the immediate ancestor checks, using native filesystem operations
  // instead of repeated PowerShell provider/OneDrive/Get-Item pipelines.
  noLinks(source);noLinks(target);
  const input=fs.openSync(source,'r'),hash=crypto.createHash('sha256');let output;
  try {
    const before=fs.fstatSync(input);if(!before.isFile())throw Error('Source is not a regular file: '+source);
    output=fs.openSync(target,'wx');let count;
    while((count=fs.readSync(input,buffer,0,buffer.length,null))>0){hash.update(buffer.subarray(0,count));let offset=0;while(offset<count)offset+=fs.writeSync(output,buffer,offset,count-offset);progress();}
    const after=fs.fstatSync(input);
    if(before.size!==after.size||before.mtimeMs!==after.mtimeMs||before.ctimeMs!==after.ctimeMs)throw Error('Source changed while copying: '+source);
    fs.closeSync(output);output=undefined;
    const sourceHash=hash.digest('hex').toUpperCase(),verify=crypto.createHash('sha256'),saved=fs.openSync(target,'r');
    try{while((count=fs.readSync(saved,buffer,0,buffer.length,null))>0){verify.update(buffer.subarray(0,count));progress();}}finally{fs.closeSync(saved);}
    if(verify.digest('hex').toUpperCase()!==sourceHash)throw Error('Backup verification failed: '+source);
    return {sha256:sourceHash,bytes:before.size};
  }finally{fs.closeSync(input);if(output!==undefined)fs.closeSync(output);}
}
// Stream the manifest; interrupted snapshots never receive a completion name.
const pending=path.join(destination,'backup-manifest.pending'),manifest=fs.openSync(pending,'wx');
fs.writeSync(manifest,'{"createdAt":'+JSON.stringify(new Date().toISOString())+',"files":[');
function visit(relative){
  const normalized=relative.split(path.sep).join('\\');
  if(exclusions.has(normalized.toLowerCase())){excluded.push({path:normalized,reason:exclusions.get(normalized.toLowerCase())});return;}
  const source=under(root,path.join(root,relative)),target=under(destination,path.join(destination,relative));
  const stat=fs.lstatSync(source);if(stat.isSymbolicLink())throw Error('Backup refuses unrecognized link outside the generated cache: '+source);
  if(stat.isDirectory()){
    noLinks(source);noLinks(target);fs.mkdirSync(target);folders++;progress();
    const directory=fs.opendirSync(source);try{let entry;while((entry=directory.readSync())!==null)visit(path.join(relative,entry.name));}finally{directory.closeSync();}
  } else if(stat.isFile()){
    const saved=hashedCopy(source,target);
    fs.writeSync(manifest,(files?',':'')+JSON.stringify({path:normalized,sha256:saved.sha256}));
    files++;bytes+=saved.bytes;progress();
  } else throw Error('Backup refuses nonregular filesystem entry: '+source);
}
try {
  progress(true);
  for(const item of items){const source=under(root,path.join(root,item));if(fs.existsSync(source))visit(item);}
  fs.writeSync(manifest,'],"excluded":'+JSON.stringify(excluded)+',"modelsExcluded":true,"verified":true}');
  fs.fsyncSync(manifest);fs.closeSync(manifest);
  noLinks(destination);fs.renameSync(pending,path.join(destination,'backup-manifest.json'));
  progress(true);process.stdout.write(JSON.stringify({verified:true,files,bytes,seconds:Math.round((Date.now()-started)/1000)})+'\n');
}catch(error){try{fs.closeSync(manifest);}catch{}throw error;}
