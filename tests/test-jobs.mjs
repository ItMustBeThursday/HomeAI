import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {spawn} from 'node:child_process';
import {JobStore,controlReply,settle,stepPrompt} from '../home-ai-kit/jobs-plugin/store.mjs';
import plugin,{createWorkbench} from '../home-ai-kit/workbench-plugin/index.mjs';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'artifacts','jobs-'+Date.now());
await fs.mkdir(root,{recursive:true});
await fs.writeFile(path.join(root,'homeai.json'),JSON.stringify({owner:'home-ai-kit-v1',root,backupRoot:path.join(root,'backups'),ollamaPort:11435}));
const store=new JobStore(root);
await assert.rejects(store.create({project:'../escape',goal:'bad',expectedFiles:['README.md']}));
await assert.rejects(store.create({project:'demo',goal:'bad',expectedFiles:['../outside.txt']}));
await assert.rejects(store.create({project:'demo',goal:'bad',maxSteps:100,expectedFiles:['README.md']}));
const job=await store.create({project:'demo',goal:'Write a project overview.',expectedFiles:['README.md'],maxSteps:2});
assert.equal((await new JobStore(root).get(job.id)).status,'queued');
assert.ok(stepPrompt(job).includes('No shell/tests'));
await store.update(job.id,j=>{j.status='running';j.dispatch={at:'fixture'};});
await store.control(job.id,'pause');
await settle(store,job.id,{decision:'continue',summary:'one step'});
assert.equal((await store.get(job.id)).status,'paused');
await store.control(job.id,'resume');
await settle(store,job.id,{decision:'ready',summary:'done'});
assert.equal((await store.get(job.id)).status,'needs-review');
assert.match((await store.get(job.id)).lastError,/ENOENT/);
await fs.mkdir(path.join(root,'projects','demo'),{recursive:true});
await fs.writeFile(path.join(root,'projects','demo','README.md'),'real output');
await store.control(job.id,'resume');
await settle(store,job.id,{decision:'ready',summary:'file present'});
const finished=await store.get(job.id);assert.equal(finished.status,'ready-for-review');assert.equal(finished.evidence[0].sha256.length,64);
assert.notEqual(finished.status,'completed');
await assert.rejects(Promise.resolve().then(()=>controlReply('All done!')));
const scope=createWorkbench(root,undefined,{projectScope:'demo'});
await assert.rejects(scope.find(t=>t.name==='homeai_project').execute('test',{action:'list',project:'other'}),/selected project/);
let factory;
plugin.register({pluginConfig:{root},registerTool:f=>{factory=f;}});
const workerTools=factory({agentId:'homeai-worker',sessionKey:'agent:homeai-worker:homeai-job-'+job.id});
assert.ok(workerTools?.length===3);assert.equal(factory({agentId:'homeai-worker',sessionKey:'agent:homeai-worker:unbound'}),null);
await assert.rejects(workerTools.find(t=>t.name==='homeai_project').execute('test',{action:'write',project:'other',file:'x.txt',content:'bad'}),/selected project/);
const lockJob=await store.create({project:'demo',goal:'Concurrent store test.',expectedFiles:['README.md']});
const moduleUrl=pathToFileURL(path.join(path.dirname(fileURLToPath(import.meta.url)),'../home-ai-kit/jobs-plugin/store.mjs')).href;
const children=Array.from({length:4},()=>new Promise((resolve,reject)=>{
 const child=spawn(process.execPath,['--input-type=module','-e',"const {JobStore}=await import(process.argv[1]); await new JobStore(process.argv[2]).update(process.argv[3],async j=>{await new Promise(r=>setTimeout(r,40));j.counter=(j.counter||0)+1;});",moduleUrl,root,lockJob.id],{shell:false,windowsHide:true,stdio:'pipe'});
 let error='';child.stderr.on('data',b=>error+=b);child.on('error',reject);child.on('exit',code=>code===0?resolve():reject(Error(error)));
}));
await Promise.all(children);assert.equal((await store.get(lockJob.id)).counter,4);
console.log('PASS: durable job records, bounded steps, pause/resume, output evidence without false completion, project-bound worker tools, unbound session refusal and cross-process locking. No inference or external network calls.');
